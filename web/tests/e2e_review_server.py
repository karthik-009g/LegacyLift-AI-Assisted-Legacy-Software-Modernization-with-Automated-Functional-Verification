"""Serve a disposable, explicitly synthetic review/export fixture for Playwright."""

from __future__ import annotations

import json
import os
import sys
from pathlib import Path

import uvicorn

from legacylift.modernization.contracts import canonical_hash

REPOSITORY = Path(__file__).resolve().parents[2]
RUN_ID = "e2e" + "0" * 29
SOURCE = (
    "from fastapi import FastAPI\n"
    "app = FastAPI(title='Synthetic review/export test only')\n"
    "@app.get('/issues/{issue_id}.json')\n"
    "def show(issue_id: int):\n"
    "    return {'issue': {'id': issue_id, 'subject': 'Synthetic fixture'}}\n"
)


def write_json(path: Path, value: dict) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(value, indent=2) + "\n", encoding="utf-8")


def prepare_fixture(home: Path) -> None:
    home.mkdir(parents=True, exist_ok=True)
    (home / ".legacylift-e2e-fixture").write_text(
        "LegacyLift disposable synthetic UI test fixture\n", encoding="utf-8", newline="\n"
    )
    source_digest = canonical_hash(SOURCE)
    guidance = {
        "status": "passed",
        "split": "guidance",
        "workflow": "read",
        "source_sha256": source_digest,
        "scenario_count": 1,
        "passed_count": 1,
        "results": [{"scenario_id": "synthetic.browser.read", "passed": True, "mismatches": []}],
    }
    held_out = {
        "status": "passed",
        "split": "held_out",
        "workflow": "read",
        "run_id": RUN_ID,
        "repair_feedback_allowed": False,
        "source_sha256": source_digest,
        "scenario_count": 1,
        "passed_count": 1,
        "results": [
            {"scenario_id": "synthetic.browser.held_out", "passed": True, "mismatches": []}
        ],
        "synthetic_fixture": True,
    }
    result = {
        "run_id": RUN_ID,
        "workflow": "read",
        "condition": "hybrid",
        "provider_policy": "synthetic_fixture",
        "max_repairs": 0,
        "attempts": [
            {
                "attempt": 0,
                "summary": "Synthetic UI fixture; not generated by a model.",
                "unknowns": ["This fixture contains no Redmine observations."],
                "evidence_ids": ["synthetic:browser-fixture"],
                "source_sha256": source_digest,
                "review": {
                    "status": "static_review_passed",
                    "certified_secure": False,
                    "findings": [],
                },
                "provenance": {
                    "provider": "synthetic fixture",
                    "model": "test only",
                    "latency_seconds": 0,
                },
                "evaluation_status": "passed",
                "passed_count": 1,
                "scenario_count": 1,
            }
        ],
        "status": "passed",
        "held_out_evaluated": True,
        "held_out_status": "passed",
        "held_out_passed_count": 1,
        "held_out_scenario_count": 1,
        "held_out_report_sha256": None,
        "human_approved": False,
        "security_certified": False,
        "candidate_path": str(home / "runs" / RUN_ID / "app.py"),
        "synthetic_fixture": True,
    }

    result["held_out_report_sha256"] = canonical_hash(held_out)
    run_directory = home / "runs" / RUN_ID
    run_directory.mkdir(parents=True, exist_ok=True)
    (run_directory / "app.py").write_text(SOURCE, encoding="utf-8")
    write_json(run_directory / "result.json", result)
    write_json(run_directory / "draft-0.json", result["attempts"][0])
    write_json(run_directory / "guidance-0.json", guidance)
    write_json(run_directory / "held-out.json", held_out)

    write_json(home / "study/oracle.json", {"synthetic_fixture": True})
    write_json(home / "study/synthetic_fixture.json", {"kind": "browser_review_export_test"})
    write_json(
        home / "evidence/redmine.json",
        {
            "method_count": 0,
            "source_file_count": 0,
            "parse_error_files": [],
            "unknowns": ["Synthetic UI test data; no source repository was analyzed."],
            "workflows": {
                name: (
                    [
                        {
                            "evidence_id": "synthetic:browser-fixture",
                            "path": "synthetic/test_fixture.rb",
                            "start_line": 1,
                            "end_line": 1,
                            "text": "# Synthetic UI fixture only; not Redmine source.\n",
                            "symbol": "synthetic_fixture",
                            "retrieval_score": 0,
                        }
                    ]
                    if name == "read"
                    else []
                )
                for name in ("read", "create", "update")
            },
            "rails_inferences": [],
        },
    )


if __name__ == "__main__":
    fixture_home = Path(sys.argv[1]).resolve()
    prepare_fixture(fixture_home)
    os.environ["LEGACYLIFT_WEB_DIST"] = str(REPOSITORY / "web" / "dist")

    from legacylift.workbench.api import create_app

    uvicorn.run(create_app(fixture_home, start_jobs=False), host="127.0.0.1", port=8011)
